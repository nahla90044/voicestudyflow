// تنظيف عناوين الأجزاء (٢٦ أكتوبر، ملاحظة نهلة): الملخّص يُكتب على أجزاء فيعنون النموذج الجزء الأول
// «… (الجزء الأول)»، فيظهر في افتتاح الفيديو كأن بعده أجزاء أخرى. يُحذف هذا الوسم من عنوان الوحدة/الفيديو.
const ORD = "(?:الأول|الاول|الثاني|الثالث|الرابع|الخامس|السادس|السابع|الثامن|التاسع|العاشر|[0-9٠-٩]+)";
const PART_RE = new RegExp(
  `\\s*[(\\[]\\s*(?:ال)?جزء\\s+${ORD}(?:\\s*(?:من|/)\\s*[0-9٠-٩]+)?\\s*[)\\]]` + // «(الجزء الأول)»، «(الجزء ٢ من ٤)»
    `|\\s*[-–—:،]\\s*(?:ال)?جزء\\s+${ORD}(?:\\s*(?:من|/)\\s*[0-9٠-٩]+)?\\s*$` + // «… — الجزء الثاني»
    `|^\\s*(?:ال)?جزء\\s+${ORD}(?:\\s*(?:من|/)\\s*[0-9٠-٩]+)?\\s*[:：\\-–—]\\s*` + // «الجزء الأول: …»
    `|\\s*\\(\\s*part\\s+\\d+(?:\\s*(?:of|/)\\s*\\d+)?\\s*\\)`,
  "gi"
);

export function stripPartMarker(t: string): string {
  const out = String(t ?? "").replace(PART_RE, "").replace(/\s{2,}/g, " ").trim();
  return out || String(t ?? "").trim();
}
