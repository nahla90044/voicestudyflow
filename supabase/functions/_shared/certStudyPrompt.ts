/** اسم الاختبار بأمان (يكتبه الطالب): حروف وأرقام ومسافات وشرطات فقط، ٦٠ حرفًا */
export const safeExam = (v: unknown) =>
  String(v ?? "")
    .replace(/[^\p{L}\p{N}\s\-—–()/.]/gu, "")
    .trim()
    .slice(0, 60);

