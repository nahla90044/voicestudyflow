export type VPartTopic = { id: string; t: string; check?: boolean; final?: boolean; example?: string; cont?: boolean; ex?: number; chars?: number };
export type VPart = {
  v: 1;
  role: "part" | "solo";
  i: number;
  n: number;
  mine: VPartTopic[];
  before: string[];
  after: string[];
  map: string[];
  scenes: number;
  exCount?: number;
  keys?: string[];
};

/** نص قصير آمن: بلا وسوم، مسافات مطويّة، حتى ١٢٠ حرفًا */
const txt = (v: unknown) =>
  String(v ?? "")
    .replace(/[<>]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120);
const int = (v: unknown, lo: number, hi: number): number | null => {
  const n = Number(v);
  return Number.isInteger(n) && n >= lo && n <= hi ? n : null;
};
const list = (v: unknown, max: number) => (Array.isArray(v) ? v.map(txt).filter(Boolean).slice(0, max) : []);

/** يقرأ نصيب الجزء من الطلب ويحصّنه؛ null إن لم يكن صالحًا (فيبقى السلوك القديم) */
export function readVpart(raw: unknown): VPart | null {
  if (!raw || typeof raw !== "object") return null;
  const o = raw as Record<string, unknown>;
  if (o.v !== 1 || (o.role !== "part" && o.role !== "solo")) return null;
  const n = int(o.n, 1, 40);
  const i = int(o.i, 0, 39);
  const scenes = int(o.scenes, 1, 40);
  if (n === null || i === null || i >= n || scenes === null) return null;
  const mine: VPartTopic[] = [];
  for (const m of Array.isArray(o.mine) ? o.mine.slice(0, 30) : []) {
    const x = (m ?? {}) as Record<string, unknown>;
    const id = String(x.id ?? "");
    const t = txt(x.t);
    if (!/^[TE]\d{1,3}$/.test(id) || !t) continue;
    const out: VPartTopic = { id, t };
    if (x.check === true) out.check = true;
    if (x.final === true) out.final = true;
    if (x.cont === true) out.cont = true;
    const ex = int(x.ex, 0, 100);
    if (id.startsWith("E") && ex !== null) out.ex = ex;
    const example = txt(x.example);
    if (example) out.example = example;
    const chars = int(x.chars, 0, 100000);
    if (chars !== null) out.chars = chars;
    mine.push(out);
  }
  if (o.role === "part" && !mine.length) return null;
  const vp: VPart = { v: 1, role: o.role, i, n, mine, before: list(o.before, 80), after: list(o.after, 80), map: list(o.map, 80), scenes };
  const exCount = int(o.exCount, 0, 100);
  if (exCount !== null) vp.exCount = exCount;
  const keys = list(o.keys, 8);
  if (keys.length) vp.keys = keys;
  return vp;
}

/** كل نصوص الخطة (لفحص المحتوى الخفي كما يُفحص نص الكتاب) */
export function vpartText(vp: VPart): string {
  return [...vp.mine.flatMap((m) => [m.t, m.example ?? ""]), ...vp.before, ...vp.after, ...vp.map, ...(vp.keys ?? [])].join("\n");
}

const q = (xs: string[]) => xs.map((x) => `«${x}»`).join("، ");

/** خطة الوحدة ونصيب الجزء منها، تُرسل للنموذج قبل نص الكتاب داخل <unit_plan> */
export function planBlock(vp: VPart): string {
  if (vp.role === "solo") {
    return [
      "<unit_plan>",
      `الفيديو كله في هذا الجزء. عدد التمارين: ${vp.exCount ?? 0}.`,
      `نقاط الخلاصة (تُذكر في الخلاصة فقط): ${vp.keys?.length ? vp.keys.join("؛ ") : "لا شيء"}.`,
      `عدد مشاهد الشرح المناسب: نحو ${vp.scenes}.`,
      "</unit_plan>",
    ].join("\n");
  }
  const topics = vp.mine.map((m) => {
    if (m.id.startsWith("E")) return `- ${m.id} تمارين «${m.t}»: ${m.ex ?? 0} تمرين، لكل تمرين مشهد check بقيمة "final":"ex"`;
    const tags = [
      m.cont ? "[تابع: بدأ في الجزء السابق، يُكمَل دون إعادة تعريف]" : "",
      m.check ? "[سؤال فهم بعده]" : "",
      m.final ? "[سؤال ختامي]" : "",
      m.example ? `[فكرة مثال: ${m.example}]` : "",
    ].filter(Boolean);
    return `- ${m.id} «${m.t}»${tags.length ? " " + tags.join(" ") : ""}`;
  });
  return [
    "<unit_plan>",
    `الجزء ${vp.i + 1} من ${vp.n} من فيديو واحد متصل.`,
    `محاور الوحدة: ${vp.map.length ? vp.map.join(" ← ") : "—"}`,
    `شُرح قبل هذا الجزء (لا يُعاد): ${vp.before.length ? q(vp.before) : "لا شيء؛ هذا أول الشرح بعد مشهد الافتتاح"}`,
    "مواضيع هذا الجزء بالترتيب:",
    ...topics,
    `يأتي بعد هذا الجزء (لا يُذكر ولا يُمهَّد له): ${vp.after.length ? q(vp.after) : "لا شيء؛ بعد هذا الجزء الخلاصة وأسئلة الوحدة"}`,
    `عدد مشاهد الشرح المناسب: نحو ${vp.scenes}.`,
    "</unit_plan>",
  ].join("\n");
}
